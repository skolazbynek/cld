# The broker client is `cld broker <action>` (cld/broker.py), not a wrapper script:
# one implementation of the ssh call, shared by the CLI and by everything that
# reaches the host through it. CLD_BROKER_ENDPOINT is [user@]host:port (default
# user: zet). See docs/design-cld-broker.md.
# Same test as cld/broker.py:broker_available -- the client always pins the
# host key, so without known_hosts every call fails.
cld_broker_wired() {
    [ -n "${CLD_BROKER_ENDPOINT:-}" ] && [ -f /run/secrets/broker-key ] && [ -f /run/secrets/broker-known-hosts ]
}
if cld_broker_wired; then
    echo "[INFO] cld broker ready: run tests via 'cld broker run-tests <pytest args>'"
fi

# Append one repo's resolved anchor as `export NAME_ANCHOR=<change id>` to
# $CLD_TICKET_ANCHOR_ENV_FILE. `docker exec` only inherits env set at
# container creation, not vars the entrypoint exports at runtime (PID 1
# idles; harness/shell sessions attach later via exec), so the anchors are
# handed to those sessions by sourcing this file instead -- see the claude
# wrapper heredoc in entrypoint-claude-devcontainer.sh and exec_shell in
# cld/ticket.py.
cld_record_anchor_env() {
    local name="$1" anchor="$2" env_name
    env_name=$(printf '%s' "$name" | tr '[:lower:]-' '[:upper:]_' | tr -cs 'A-Z0-9_' '_')
    printf 'export %s_ANCHOR=%q\n' "$env_name" "$anchor" >> "$CLD_TICKET_ANCHOR_ENV_FILE"
}

# Look up one repo's value in a per-repo env encoding: "<name>=<value>;..."
# (CLD_REPO_BOOTSTRAP). Echoes nothing when the name is absent.
cld_repo_kv_get() {
    local encoded="$1" name="$2" part
    local IFS=';'
    for part in $encoded; do
        case "$part" in
            "$name="*) printf '%s' "${part#"$name"=}"; return 0 ;;
        esac
    done
    return 0
}

# Generate the ticket-root CLAUDE.md so a fresh harness session orients itself
# (PRODUCT_DESIGN.md section 3). Derived state, regenerated on every boot,
# never edited. Args: $1=ticket root dir, $2=ticket slug, $3=pre-built table
# rows "| name | anchor | mode | backend |\n..." from the boot loop.
write_ticket_claude_md() {
    local ticket_root="$1" ticket="$2" rows="$3"
    cat > "$ticket_root/CLAUDE.md" <<EOF
# Ticket: ${ticket}

Generated by the cld entrypoint on every boot -- do not edit, edits are lost.

Each subdirectory below is one repo's workspace, mounted for this ticket:

| Repo | Anchor | Mode | Backend |
|---|---|---|---|
${rows}
Anchor contract: in each repo, create and edit only changes descending from
that repo's anchor above. The anchor is a jj change ID (a commit hash on git).
The host may rebase the anchor, which changes its commit hash but not its
change ID. Never rewrite, move or rebase the anchor yourself. Shared mode
widens the editable tree to every descendant of the anchor; isolated mode
(default) means only your own work descends from it.

/workspace/origin/<repo> holds only the shared jj/git store. Run jj and edit files in your workspace.

Each repo's own CLAUDE.md governs work in its subtree.

## Bookmark names

Every bookmark you create starts with this ticket's identifier \`t.${ticket}\`.

- \`t.${ticket}\` is the session bookmark: never move or delete it.
- Merge request branches: \`t.${ticket}.mr\`, or \`t.${ticket}.mr-<word>\` for
  several (\`<word>\`: lowercase letters, digits, dashes).
- Any other bookmark: \`t.${ticket}.<word>\` (more dotted words may follow).
- Never use \`internal.\`: it belongs to host automation.
EOF
    local has_git=0
    [[ "$rows" == *"| git |"* ]] && has_git=1
    if [ "$has_git" = 1 ]; then
        cat >> "$ticket_root/CLAUDE.md" <<EOF

## Git repos

For a repo whose Backend above is \`git\`, the workspace is a git worktree on
the branch \`t.${ticket}\`, and the bookmark rules above apply to branches:

- \`t.${ticket}\` is the session branch: never delete it or switch the
  workspace off it. Every other branch you create starts with \`t.${ticket}\`.
- The anchor of a git repo is the scratch commit \`cld anchor: t.${ticket} ...\`
  (isolated) or its parent (shared), pinned by the hidden ref
  \`refs/cld/anchor/t.${ticket}\`. Never move or delete that ref. \`HEAD\` must
  stay on a descendant of the anchor. A host rebase does not move the anchor;
  only \`cld restart --reanchor\` does.
- Commit with \`git add\` and \`git commit\`. The session branch advances
  with each commit; uncommitted edits are not part of any shared state.
- Push a merge request with \`git push origin HEAD:t.${ticket}.mr\` (or
  \`HEAD:t.${ticket}.mr-<word>\`).
EOF
    fi
    if cld_broker_wired; then
        cat >> "$ticket_root/CLAUDE.md" <<'EOF'

## Tests and the live GraphQL server

Run the test suite and the GraphQL server through the cld broker. It runs
them on the host, with the repo's real secrets (this container has none),
against your latest edits -- uncommitted ones included.

- Tests: `cld broker run-tests [--repo <name>] [pytest args]` -- skill `broker-run-tests`.
- Server: the `graphql-tester` MCP tools (`start_server`, `query`,
  `restart_server` after edits) -- skill `broker-graphql-server`.

Pass the repo name (`--repo <name>`, tool argument `repo`) only when this
ticket mounts more than one repo.
EOF
        if [ "$has_git" = 1 ]; then
            cat >> "$ticket_root/CLAUDE.md" <<EOF

For a git repo the broker sees committed work only: it tests the tip of the
branch \`t.${ticket}\`, not your working tree. Commit before you run tests
or restart the server.
EOF
        fi
    fi
    echo "[cld] wrote ${ticket_root}/CLAUDE.md"
}

# Create this container's own mailbox dirs under the shared mailbox mount.
# No-op if the mailbox tree isn't mounted (one-shot `cld run` sessions).
ensure_own_mailbox() {
    local mailbox_base="/var/cld/mailboxes"
    [ -d "$mailbox_base" ] || return 0
    local name="${SESSION_NAME:?SESSION_NAME must be set}"
    if ! mkdir -p "$mailbox_base/$name/tmp" "$mailbox_base/$name/inbox" "$mailbox_base/$name/archive" 2>/tmp/mailbox-mkdir-err; then
        cat /tmp/mailbox-mkdir-err >&2
        echo "[ERROR] Could not write to $mailbox_base (running as uid=$(id -u) gid=$(id -g))." >&2
        echo "        The host directory bind-mounted here is missing, stale, or owned by someone" >&2
        echo "        else. From the HOST (not this container), find its source path and fix it:" >&2
        echo "          docker inspect $name --format '{{range .Mounts}}{{if eq .Destination \"$mailbox_base\"}}{{.Source}}{{end}}{{end}}'" >&2
        echo "          chown -R $(id -u):$(id -g) <path printed above>" >&2
        return 1
    fi
}

# Seed ~/.ssh/known_hosts from the repo's SSH remote.
# The host's known_hosts is copied in with the ssh-agent forward; this covers a
# remote the host never accepted, which would otherwise fail a first push with
# "Host key verification failed". Best-effort: no remote, an https remote, or no
# network all just skip (the push, if any, will report the real problem).
seed_known_hosts() {
    local url host
    url=$(jj git remote list 2>/dev/null | awk '$1 == "origin" {print $2; exit}')
    [ -n "$url" ] || url=$(git -C "$WORKSPACE_ORIGIN" remote get-url origin 2>/dev/null)
    case "$url" in
        *@*:*)      host="${url#*@}"; host="${host%%:*}" ;;
        ssh://*)    host="${url#ssh://}"; host="${host#*@}"; host="${host%%[:/]*}" ;;
        *)          return 0 ;;
    esac
    [ -n "$host" ] || return 0
    mkdir -p ~/.ssh && chmod 700 ~/.ssh
    # -f pins the file: ssh-keygen otherwise resolves ~ from the passwd database
    # rather than $HOME, so the already-seeded check would read the wrong file.
    if [ -f ~/.ssh/known_hosts ] && ssh-keygen -F "$host" -f ~/.ssh/known_hosts >/dev/null 2>&1; then
        return 0
    fi
    if ssh-keyscan -t rsa,ecdsa,ed25519 "$host" 2>/dev/null >> ~/.ssh/known_hosts; then
        chmod 600 ~/.ssh/known_hosts
        echo "[cld] seeded ~/.ssh/known_hosts for $host"
    else
        echo "[WARN] could not ssh-keyscan $host -- a push to it may fail host-key verification" >&2
    fi
}

# Copy staged host config tree into $HOME.
# Every RO $HOME mount is staged under /tmp/host-config/<rel> by the launcher;
# we overlay that tree onto $HOME so the container has writable copies and
# Docker never creates $HOME subdirs as root.
copy_host_configs() {
    local src_root="/tmp/host-config"
    if [ -d "$src_root" ]; then
        cp -aT "$src_root" "$HOME"
        # Only chmod the paths we just staged, not the whole $HOME (~635M of baked caches).
        (cd "$src_root" && find . -mindepth 1 -print0) | \
            (cd "$HOME" && xargs -0 -r chmod u+w) 2>/dev/null || true
    fi
    cld_disable_git_hooks
}

# Git hooks off in every container, as jj never runs them. A worktree takes its
# hooks from the common dir, which is the host's hooks mounted read-only, and a
# host hook may call a host-only path. The repo config is read-only too, so the
# switch lives in the global config, written after the copy above so it lands on
# top of the user's staged ~/.gitconfig and keeps its identity.
cld_disable_git_hooks() {
    local hooks_dir="$HOME/.cld-no-hooks"
    mkdir -p "$hooks_dir" && git config --global core.hooksPath "$hooks_dir" ||
        echo "[WARN] could not turn off git hooks: a host hook may block git commit" >&2
    return 0
}

# Build container-local claude.json from read-only host config.
# Merges global and host-project MCP servers into user scope (top-level mcpServers)
# so they're available regardless of which project directory claude runs in.
build_claude_config() {
    local host_config="/tmp/host-config/.claude.json"
    [ -f "$host_config" ] || return 0

    if ! command -v jq &>/dev/null; then
        cp "$host_config" "$HOME/.claude.json"
        return 0
    fi

    local global_mcp host_mcp
    global_mcp=$(jq -c '.mcpServers // {}' "$host_config" 2>/dev/null || echo '{}')
    host_mcp='{}'
    # v1 kinds: merge the host project's own MCP servers on top of the global
    # ones. The launcher sets CLD_HOST_PROJECT_DIR (this used to read the
    # never-set HOST_PROJECT_DIR, so the per-project merge never fired --
    # docs/design-ticket-containers.md section 9). Ticket containers set
    # neither and merge global-scope servers only: there is no single host
    # project to merge from (a per-repo project-scope merge is a later nicety).
    if [ -n "${CLD_HOST_PROJECT_DIR:-}" ]; then
        host_mcp=$(jq -c --arg p "$CLD_HOST_PROJECT_DIR" '.projects[$p].mcpServers // {}' "$host_config" 2>/dev/null || echo '{}')
    fi

    if jq --argjson g "$global_mcp" --argjson h "$host_mcp" \
       '.mcpServers = ($g + $h)' \
       "$host_config" > "$HOME/.claude.json" 2>/dev/null; then
        echo "MCP servers configured (user scope)"
    else
        cp "$host_config" "$HOME/.claude.json"
    fi

    # Rewrite baked-in MCP servers to use container paths. graphql-tester is
    # also added wherever the broker is wired: its tools are only broker
    # clients, so it needs no registration on the host.
    local rewrites='{}'
    if jq -e '.mcpServers["graphql-tester"]' "$HOME/.claude.json" &>/dev/null || cld_broker_wired; then
        rewrites=$(echo "$rewrites" | jq '.["graphql-tester"] = {
            "type": "stdio",
            "command": "python3",
            "args": ["/opt/cld/cld/mcp/graphql.py"]
        }')
    fi
    if jq -e '.mcpServers.messenger' "$HOME/.claude.json" &>/dev/null; then
        rewrites=$(echo "$rewrites" | jq '.messenger = {
            "type": "stdio",
            "command": "python3",
            "args": ["/opt/cld/cld/mcp/messenger.py"]
        }')
    fi
    if [ "$rewrites" != '{}' ]; then
        jq --argjson r "$rewrites" '.mcpServers += $r' \
            "$HOME/.claude.json" > /tmp/claude-json-tmp && \
            mv /tmp/claude-json-tmp "$HOME/.claude.json"
        echo "MCP servers rewritten for container: $(echo "$rewrites" | jq -r 'keys | join(", ")')"
    fi

    # Arguments are workspace paths claude must treat as trusted, so the
    # "trust this workspace" dialog never blocks a container session.
    if [ "$#" -gt 0 ]; then
        jq 'reduce $ARGS.positional[] as $p (.; .projects[$p].hasTrustDialogAccepted = true)' \
            --args "$@" < "$HOME/.claude.json" > /tmp/claude-json-tmp && \
            mv /tmp/claude-json-tmp "$HOME/.claude.json"
    fi
}
